// Generates worker/src/sites.generated.ts from data-src/sites.json (falls back to a short inline list).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "data-src", "sites.json");
const out = join(root, "worker", "src", "sites.generated.ts");
const MAX_BYTES = 2000;

const fallback = [
  ["apollo11", "Apollo 11"], ["apollo12", "Apollo 12"], ["apollo14", "Apollo 14"],
  ["apollo15", "Apollo 15"], ["apollo16", "Apollo 16"], ["apollo17", "Apollo 17"],
  ["shackleton", "Shackleton rim"], ["malapert", "Malapert massif"],
  ["haworth", "Haworth"], ["nobile", "Nobile"], ["connecting_ridge", "Connecting Ridge"],
];

let entries = fallback;
let from = "inline fallback";
if (existsSync(src)) {
  try {
    const arr = JSON.parse(readFileSync(src, "utf8"));
    if (Array.isArray(arr) && arr.length) {
      entries = arr.filter((s) => s && s.id).map((s) => [String(s.id), String(s.name ?? s.id)]);
      from = "data-src/sites.json";
    }
  } catch (e) {
    console.warn("gen-sites: could not parse sites.json, using fallback:", e.message);
  }
}

// Compact "id=Short name" list; shorten names (drop parentheticals) and trim to budget.
const short = (n) => n.replace(/\s*\(.*?\)\s*/g, " ").trim();
let lines = entries.map(([id, name]) => `${id}=${short(name)}`);
let text = lines.join("; ");
while (Buffer.byteLength(text) > MAX_BYTES && lines.length > 1) {
  lines.pop();
  text = lines.join("; ");
}
const ids = lines.map((l) => l.split("=")[0]);
const body =
  `// GENERATED by scripts/gen-sites.mjs from ${from}. Do not edit.\n` +
  `export const SITE_LIST_TEXT = ${JSON.stringify(text)};\n` +
  `export const SITE_IDS: string[] = ${JSON.stringify(ids)};\n`;
writeFileSync(out, body);
console.log(`gen-sites: ${ids.length} sites from ${from} (${Buffer.byteLength(text)} bytes)`);
